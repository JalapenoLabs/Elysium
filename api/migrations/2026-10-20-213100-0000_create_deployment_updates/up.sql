-- Every update the deployment's updater applied, or tried to apply and rolled back. The API
-- tells the updater which release to apply and records the outcome it reports, so Settings
-- shows the history and a release that failed is not offered again. See docs/infrastructure.md.

CREATE TYPE deployment_update_status AS ENUM (
    -- The updater was told to apply the release and has not reported back.
    'applying',
    -- The release is running and healthy.
    'succeeded',
    -- The release did not come up healthy, and the updater restored the previous one.
    'rolled_back'
);

CREATE TABLE deployment_updates (
    -- Generated by the API (UUIDv7), so ids order updates the way they began.
    id UUID PRIMARY KEY,
    -- Releases, as X.Y.Z.
    from_version TEXT NOT NULL,
    to_version TEXT NOT NULL,
    status deployment_update_status NOT NULL DEFAULT 'applying',
    -- What went wrong; set exactly when the update rolled back.
    reason TEXT,
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Set exactly once the update leaves applying.
    finished_at TIMESTAMPTZ,
    -- The admin who asked for it, or the system user for an automatic update.
    created_by UUID NOT NULL REFERENCES users (id),

    CONSTRAINT deployment_updates_versions_shape CHECK (
        from_version ~ '^[0-9]+\.[0-9]+\.[0-9]+$' AND to_version ~ '^[0-9]+\.[0-9]+\.[0-9]+$'
    ),
    CONSTRAINT deployment_updates_finished_once_done CHECK (
        (status = 'applying') = (finished_at IS NULL)
    ),
    CONSTRAINT deployment_updates_reason_when_rolled_back CHECK (
        (status = 'rolled_back') = (reason IS NOT NULL)
    ),
    CONSTRAINT deployment_updates_reason_length CHECK (char_length(reason) BETWEEN 1 AND 2000)
);

-- One update at a time: another cannot begin while one is applying.
CREATE UNIQUE INDEX deployment_updates_one_applying ON deployment_updates ((true))
    WHERE status = 'applying';
