-- Nightly backups of the databases the stack keeps (Elysium's own, Kratos's, and Hydra's) to a
-- storage location off the host. Every attempt is a row, so Settings shows the history and the
-- schedule knows whether tonight's backup is done. See docs/infrastructure.md, Backups.

CREATE TYPE database_backup_status AS ENUM (
    -- Dumping and uploading.
    'running',
    -- Every database's dump is stored in the location.
    'succeeded',
    -- Something failed; what this attempt uploaded was removed again.
    'failed'
);

CREATE TYPE database_backup_trigger AS ENUM (
    -- The nightly schedule.
    'schedule',
    -- An admin's Back up now.
    'admin',
    -- The deployment's own tooling, before it changes the stack.
    'deployment'
);

CREATE TABLE database_backups (
    -- Generated by the API (UUIDv7), so ids order backups the way they began.
    id UUID PRIMARY KEY,
    trigger database_backup_trigger NOT NULL,
    status database_backup_status NOT NULL DEFAULT 'running',
    -- Where the files went. A location cannot be deleted while backups go to it; one that stopped
    -- being the destination may be, and its past backups keep their row without it.
    storage_location_id UUID REFERENCES storage_locations (id) ON DELETE SET NULL,
    -- Names every file of the backup, `<started_at>-<database>.dump`, to the second.
    started_at TIMESTAMPTZ NOT NULL,
    -- Set exactly once it leaves running.
    finished_at TIMESTAMPTZ,
    -- Every dump together; set exactly when it succeeded.
    size_bytes BIGINT,
    -- What went wrong; set exactly when it failed.
    error TEXT,
    -- The admin who asked for it, or the system user for the schedule and the deployment.
    created_by UUID NOT NULL REFERENCES users (id),

    CONSTRAINT database_backups_finished_once_done CHECK (
        (status = 'running') = (finished_at IS NULL)
    ),
    CONSTRAINT database_backups_size_when_succeeded CHECK (
        (status = 'succeeded') = (size_bytes IS NOT NULL)
    ),
    CONSTRAINT database_backups_size_not_negative CHECK (size_bytes >= 0),
    CONSTRAINT database_backups_error_when_failed CHECK (
        (status = 'failed') = (error IS NOT NULL)
    ),
    CONSTRAINT database_backups_error_length CHECK (char_length(error) BETWEEN 1 AND 2000)
);

-- One backup at a time: another cannot begin while one is running.
CREATE UNIQUE INDEX database_backups_one_running ON database_backups ((true))
    WHERE status = 'running';

-- The schedule reads tonight's attempts, and Settings the newest few.
CREATE INDEX database_backups_started_at ON database_backups (started_at DESC);

-- The storage location backups go to, chosen by an admin; NULL until one is, and until then
-- nothing is backed up. Deleting the location is refused while it is chosen.
ALTER TABLE workspace_settings
    ADD COLUMN backup_storage_location_id UUID
        CONSTRAINT workspace_settings_backup_storage_location REFERENCES storage_locations (id);

-- A backup that failed for the night raises an inbox item as Elysium itself, `system`: the actor
-- for Elysium reporting on its own work.
ALTER TABLE action_item_events DROP CONSTRAINT action_item_events_actor_shape;
ALTER TABLE action_item_events ADD CONSTRAINT action_item_events_actor_shape CHECK (
    actor ~ '^(user|user:[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}|elysia|session:[1-9][0-9]*|watcher:[a-z][a-z0-9-]*|system)$'
);

ALTER TABLE action_item_comments DROP CONSTRAINT action_item_comments_author_shape;
ALTER TABLE action_item_comments ADD CONSTRAINT action_item_comments_author_shape CHECK (
    author ~ '^(user|user:[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}|elysia|session:[1-9][0-9]*|watcher:[a-z][a-z0-9-]*|system)$'
);
