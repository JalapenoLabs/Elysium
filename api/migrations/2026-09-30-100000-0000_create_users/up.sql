-- What admins did to accounts and workspace settings, and what people did to their own: one
-- row per change, with the values before and after.
CREATE TABLE user_events (
    -- Generated by the API (UUIDv7), so ids order events the way they happened.
    id UUID PRIMARY KEY,
    -- Whose account changed; NULL for a workspace setting, or once a rejected sign-up is gone.
    user_id UUID REFERENCES users (id) ON DELETE SET NULL,
    -- Who changed it. A person signing up or editing their own profile is their own actor, so
    -- this is NULL too once their rejected sign-up is gone.
    actor_id UUID REFERENCES users (id) ON DELETE SET NULL,
    kind TEXT NOT NULL,
    data JSONB NOT NULL DEFAULT '{}',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT user_events_kind_shape CHECK (kind ~ '^[a-z][a-z_]{0,63}$'),
    CONSTRAINT user_events_data_object CHECK (jsonb_typeof(data) = 'object')
);

CREATE INDEX user_events_user_id_idx ON user_events (user_id, id) WHERE user_id IS NOT NULL;
