-- Users: every principal that can create or change something in Elysium. See docs/auth.md.
--
-- People sign in through Ory Kratos, which holds their passwords, passkeys, authenticators,
-- and sessions; a person's row names its Kratos identity. Machines (the system, Elysia, and
-- coding agents) are seeded here, can never sign in, and exist so that every row can name
-- who created it.

-- What a principal may do. People are admins, members, or guests; machines are agents or the
-- system. A pending person has no role until an admin approves them.
CREATE TYPE user_role AS ENUM (
    'admin',
    'member',
    'guest',
    'agent',
    'system'
);

-- Where a person's account stands. Machines have none.
CREATE TYPE user_status AS ENUM (
    -- Signed up, waiting for an admin. Can sign in, and reach nothing but their own account.
    'pending',
    'active',
    -- Refused at sign-in and on every request. Never deleted: rows they created name them.
    'disabled'
);

CREATE TABLE users (
    -- Generated by the API (UUIDv7) for people; fixed for the seeded machines below.
    id UUID PRIMARY KEY,
    -- The Kratos identity a person signs in as. Machines have none.
    kratos_identity_id UUID UNIQUE,
    -- A person's email and name, as Kratos last reported them. Kratos is the source of truth;
    -- this copy lets lists and "created by" show people without asking Kratos.
    email TEXT UNIQUE,
    name TEXT NOT NULL,
    role user_role,
    status user_status,
    -- When they were approved; NULL for machines and pending people. The first person is
    -- approved as they sign up.
    approved_at TIMESTAMPTZ,
    -- When they last made a request, to within a few minutes.
    last_seen_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT users_name_length CHECK (char_length(name) BETWEEN 1 AND 100),
    CONSTRAINT users_email_length CHECK (char_length(email) BETWEEN 3 AND 320),
    CONSTRAINT users_email_lowercase CHECK (email = lower(email)),
    -- A principal is exactly one of these. A machine can never hold a Kratos identity, so it
    -- can never sign in; a person can never hold a machine's role.
    CONSTRAINT users_person_or_machine CHECK (
        (
            kratos_identity_id IS NULL
            AND email IS NULL
            AND status IS NULL
            AND role IS NOT NULL
            AND role IN ('agent', 'system')
        )
        OR (
            kratos_identity_id IS NOT NULL
            AND email IS NOT NULL
            AND status IS NOT NULL
            AND (role IS NULL OR role IN ('admin', 'member', 'guest'))
        )
    ),
    -- A person has a role exactly when they are no longer pending.
    CONSTRAINT users_pending_has_no_role CHECK (status IS NULL OR (status = 'pending') = (role IS NULL))
);

