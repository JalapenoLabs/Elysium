-- Workspace-wide settings admins change. One row, always present.
CREATE TABLE workspace_settings (
    singleton BOOLEAN PRIMARY KEY DEFAULT TRUE,
    -- Whether anyone may sign up. The first person may sign up either way.
    signup_open BOOLEAN NOT NULL DEFAULT TRUE,
    -- Whether every person must enroll an authenticator app before reaching the workspace.
    require_mfa BOOLEAN NOT NULL DEFAULT FALSE,
    updated_by UUID NOT NULL REFERENCES users (id),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT workspace_settings_one_row CHECK (singleton)
);

