-- Elysia, Elysium's AI assistant: what she is told, what she does, what she asks, and what she
-- is working on. See docs/elysia.md.

-- Whether Elysia may start work, and the session she carries from turn to turn. One row.
CREATE TABLE elysia_state (
    singleton BOOLEAN PRIMARY KEY DEFAULT TRUE,
    -- Set by a person: no new turn starts until it is cleared. A turn already running finishes.
    paused BOOLEAN NOT NULL DEFAULT FALSE,
    -- When she may start work on her own, as UTC minute-of-week ranges (Monday 00:00 UTC is 0).
    -- Empty means any time. A person's own messages are answered whatever this says.
    availability JSONB NOT NULL DEFAULT '[]',
    -- Set when her subscriptions report a usage limit: nothing starts before this time.
    usage_paused_until TIMESTAMPTZ,
    -- The Claude Code session her turns resume, so she carries context across turns.
    runner_session_id TEXT,
    updated_by UUID NOT NULL REFERENCES users (id),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT elysia_state_one_row CHECK (singleton),
    CONSTRAINT elysia_state_availability_array CHECK (jsonb_typeof(availability) = 'array')
);

