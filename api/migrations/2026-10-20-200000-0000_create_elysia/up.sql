-- The conversation between the people of the workspace and Elysia. A message is Elysia's when
-- `created_by` is her seeded user; messages are never edited.
CREATE TABLE elysia_messages (
    -- Generated by the API (UUIDv7), so ids order messages the way they were sent.
    id UUID PRIMARY KEY,
    body TEXT NOT NULL,
    created_by UUID NOT NULL REFERENCES users (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT elysia_messages_body_length CHECK (char_length(body) BETWEEN 1 AND 20000)
);

CREATE TYPE elysia_turn_status AS ENUM (
    -- Waiting to start: Elysia is busy, paused, outside her hours, or has no runner.
    'queued',
    'running',
    'succeeded',
    -- It ended without finishing; `error` says why.
    'failed',
    -- A person withdrew it before it started.
    'cancelled'
);

-- One run of Elysia's session, and what started it.
CREATE TABLE elysia_turns (
    id UUID PRIMARY KEY,
    -- What started it: `message` (a person wrote to her), `event` (something changed in the
    -- workspace or a provider), or `idle` (nothing was queued, so she revisits her work).
    -- Text, so later sources add kinds without a migration.
    trigger_kind TEXT NOT NULL,
    -- What the trigger carried: the message id, or the events batched into this turn.
    trigger_detail JSONB NOT NULL DEFAULT '{}',
    status elysia_turn_status NOT NULL DEFAULT 'queued',
    -- One or two sentences on what the turn did, written when it ends.
    summary TEXT,
    error TEXT,
    -- Who caused it: the person who wrote, or the system user for events and idle turns.
    created_by UUID NOT NULL REFERENCES users (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,

    CONSTRAINT elysia_turns_trigger_kind_shape CHECK (trigger_kind ~ '^[a-z][a-z-]{0,39}$'),
    CONSTRAINT elysia_turns_trigger_detail_object CHECK (jsonb_typeof(trigger_detail) = 'object'),
    CONSTRAINT elysia_turns_summary_length CHECK (char_length(summary) BETWEEN 1 AND 1000),
    CONSTRAINT elysia_turns_error_length CHECK (char_length(error) BETWEEN 1 AND 2000),
    CONSTRAINT elysia_turns_started_at_set CHECK ((started_at IS NULL) = (status IN ('queued', 'cancelled'))),
    CONSTRAINT elysia_turns_finished_at_set
        CHECK ((finished_at IS NULL) = (status IN ('queued', 'running', 'cancelled'))),
    CONSTRAINT elysia_turns_error_set CHECK ((error IS NOT NULL) = (status = 'failed'))
);

-- The queue is read oldest first, and only queued and running turns are looked at often.
CREATE INDEX elysia_turns_active ON elysia_turns (created_at) WHERE status IN ('queued', 'running');

CREATE TYPE elysia_question_status AS ENUM (
    'open',
    'answered',
    -- A person closed it without answering.
    'dismissed'
);

-- What Elysia asks a person when she is blocked, with up to four suggested answers.
CREATE TABLE elysia_questions (
    id UUID PRIMARY KEY,
    prompt TEXT NOT NULL,
    -- Suggested answers, as a JSON array of strings. A person may answer in their own words.
    options JSONB NOT NULL DEFAULT '[]',
    status elysia_question_status NOT NULL DEFAULT 'open',
    answer TEXT,
    -- The action item the question is about, if any.
    action_item_id UUID REFERENCES action_items (id) ON DELETE SET NULL,
    created_by UUID NOT NULL REFERENCES users (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    answered_by UUID REFERENCES users (id),
    answered_at TIMESTAMPTZ,

    CONSTRAINT elysia_questions_prompt_length CHECK (char_length(prompt) BETWEEN 1 AND 2000),
    CONSTRAINT elysia_questions_options_shape
        CHECK (jsonb_typeof(options) = 'array' AND jsonb_array_length(options) <= 4),
    CONSTRAINT elysia_questions_answer_length CHECK (char_length(answer) BETWEEN 1 AND 2000),
    CONSTRAINT elysia_questions_answer_set CHECK ((answer IS NOT NULL) = (status = 'answered')),
    CONSTRAINT elysia_questions_answered_set
        CHECK ((answered_at IS NULL) = (status = 'open') AND (answered_by IS NULL) = (status = 'open'))
);

CREATE INDEX elysia_questions_open ON elysia_questions (created_at) WHERE status = 'open';

CREATE TYPE elysia_work_status AS ENUM (
    -- She is on it.
    'working',
    -- Done on her side and waiting for a person's review.
    'ready',
    -- She cannot continue until something changes, such as an answer to her question.
    'blocked',
    -- She stopped trying. The idle loop revisits it after a cooldown.
    'gave-up',
    -- Finished and reviewed, or no longer needed.
    'done'
);

-- What Elysia has taken on, so people can see what she is doing and when it will be ready.
CREATE TABLE elysia_work (
    id UUID PRIMARY KEY,
    title TEXT NOT NULL,
    -- Where it stands, in her words.
    detail TEXT NOT NULL DEFAULT '',
    status elysia_work_status NOT NULL DEFAULT 'working',
    -- Her estimate of when it is ready for review, while she works on it.
    ready_at TIMESTAMPTZ,
    -- The action item it serves, if any.
    action_item_id UUID REFERENCES action_items (id) ON DELETE SET NULL,
    -- How many times she has come back to it after giving up or being blocked.
    revisits INTEGER NOT NULL DEFAULT 0,
    revisited_at TIMESTAMPTZ,
    created_by UUID NOT NULL REFERENCES users (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT elysia_work_title_length CHECK (char_length(title) BETWEEN 1 AND 200),
    CONSTRAINT elysia_work_detail_length CHECK (char_length(detail) <= 2000),
    CONSTRAINT elysia_work_revisits_non_negative CHECK (revisits >= 0)
);

SELECT diesel_manage_updated_at('elysia_work');

CREATE INDEX elysia_work_unfinished ON elysia_work (updated_at) WHERE status <> 'done';
