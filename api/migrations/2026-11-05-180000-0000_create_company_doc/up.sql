-- A change to one section that someone other than a person editing the doc suggested, waiting
-- for a person to approve or reject it.
CREATE TABLE company_doc_proposals (
    -- Generated by the API (UUIDv7), so proposals order as they were made.
    id UUID PRIMARY KEY,
    section TEXT NOT NULL REFERENCES company_doc_sections (section),
    -- The section as it read when the change was proposed, and as it would read after. Approving
    -- a proposal whose section changed since merges the two changes, three ways, and refuses one
    -- whose changes overlap.
    base_content TEXT NOT NULL CHECK (char_length(base_content) <= 12000),
    content TEXT NOT NULL CHECK (char_length(content) <= 12000),
    -- Why, and where it was read: a quote and its source, as a changeset's operations carry.
    reason TEXT NOT NULL CHECK (char_length(reason) BETWEEN 1 AND 2000),
    quote TEXT CHECK (char_length(quote) BETWEEN 1 AND 2000),
    source TEXT CHECK (char_length(source) BETWEEN 1 AND 500),
    -- The timeline record the review read it in, while it exists. A record belongs to its owner,
    -- so the doc shows the quote and source it was proposed with rather than opening the record.
    timeline_record_id UUID REFERENCES timeline_records (id) ON DELETE SET NULL,
    -- The scheduled review's run that proposed it, while the run exists.
    workflow_run_id UUID REFERENCES workflow_runs (id) ON DELETE SET NULL,
    state TEXT NOT NULL DEFAULT 'pending' CHECK (state IN ('pending', 'approved', 'rejected')),
    decided_by UUID REFERENCES users (id),
    decided_at TIMESTAMPTZ,
    -- Who proposed it: a person whose MCP client did, or the machine user of an agent of
    -- Elysium's own (Elysia for her turns and the review, the coding agent for sessions).
    created_by UUID NOT NULL REFERENCES users (id),
    -- The agent acting for them: an MCP client, as `mcp:<client id>`, or a coding or Studio
    -- session's agent, as `session:<number>`. NULL for Elysia and the review.
    agent TEXT CHECK (agent ~ '^(mcp:[^[:space:]]{1,255}|session:[0-9]{1,18})$'),
    -- What an MCP client called itself. A label only; `agent` is the identity.
    agent_name TEXT CHECK (char_length(agent_name) BETWEEN 1 AND 200),
    created_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT company_doc_proposals_changes_something CHECK (content <> base_content),
    CONSTRAINT company_doc_proposals_decided_once CHECK (
        (state = 'pending') = (decided_by IS NULL) AND (decided_by IS NULL) = (decided_at IS NULL)
    ),
    CONSTRAINT company_doc_proposals_agent_named_with_its_agent CHECK (
        agent IS NOT NULL OR agent_name IS NULL
    )
);

-- The same change is pending once, however many times it is proposed: a review step that runs
-- again, or two agents that read the same message, meet the proposal already there. Indexed by
-- the text's md5, which Postgres marks immutable, since a section's text can outgrow a btree
-- entry; it only tells proposals apart, so collisions need no resistance to attack.
CREATE UNIQUE INDEX company_doc_proposals_pending_once
    ON company_doc_proposals (section, md5(content))
    WHERE state = 'pending';

-- What waits for a person, and what a person already rejected, which the review reads so it
-- does not propose it again.
CREATE INDEX company_doc_proposals_by_state ON company_doc_proposals (state, id);

-- The doc's history, one entry per change, shaped like learning_events: `data.changes` holds each
-- section's text before and after, enough to show a change and to undo it.
CREATE TABLE company_doc_events (
    -- UUIDv7, so entries order as they were written.
    id UUID PRIMARY KEY,
    -- `edited` (a person's own change, or an undo) or `approved` (a proposal applied). Text rather
    -- than an enum, so a later kind needs no enum migration.
    kind TEXT NOT NULL CHECK (kind ~ '^[a-z][a-z_]{0,63}$'),
    -- Who made the change: the person who edited, approved, or undid.
    created_by UUID NOT NULL REFERENCES users (id),
    -- The proposal an `approved` entry applied.
    proposal_id UUID REFERENCES company_doc_proposals (id),
    data JSONB NOT NULL CHECK (jsonb_typeof(data) = 'object'),
    created_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT company_doc_events_approval_names_its_proposal CHECK (
        (kind = 'approved') = (proposal_id IS NOT NULL)
    )
);

-- How far the scheduled review has read the timeline: the last record it read, by when it was
-- ingested and then its id, so records ingested in the same instant are each read once. One row;
-- NULL until the first review, which reads back a fixed window (crate::company_doc::review).
CREATE TABLE company_doc_review_cursor (
    singleton BOOLEAN PRIMARY KEY DEFAULT TRUE,
    reviewed_through_at TIMESTAMPTZ,
    -- Not a reference: the record may be deleted, and the position stays where it was.
    reviewed_through_id UUID,
    created_by UUID NOT NULL REFERENCES users (id),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT company_doc_review_cursor_one_row CHECK (singleton),
    CONSTRAINT company_doc_review_cursor_whole CHECK (
        (reviewed_through_at IS NULL) = (reviewed_through_id IS NULL)
    )
);

SELECT diesel_manage_updated_at('company_doc_review_cursor');

