-- The company doc: one document per instance that knows the company (who it is, its leadership,
-- its people and how their names are spelled, stakeholders, products, projects, and a glossary of
-- names and jargon). People edit it directly; everyone else, the scheduled review and agents,
-- proposes changes one section at a time, and nothing changes until a person approves each one.
-- See docs/knowledge.md, The company doc.

-- The doc's fixed sections, one row each, seeded below. A section is named by its key; the order
-- they are shown and read in is fixed in code (crate::company_doc::Section).
CREATE TABLE company_doc_sections (
    section TEXT PRIMARY KEY CHECK (
        section IN (
            'company', 'leadership', 'people', 'stakeholders', 'products', 'projects', 'glossary'
        )
    ),
    -- Markdown. At most 12,000 characters, so the whole doc fits the review's one prompt beside
    -- what it reads (crate::company_doc::review, Size).
    content TEXT NOT NULL DEFAULT '' CHECK (char_length(content) <= 12000),
    created_by UUID NOT NULL REFERENCES users (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

