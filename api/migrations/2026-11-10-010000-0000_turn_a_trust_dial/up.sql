-- The trust dial: each project's one level of autonomy, which says what of its Project Manager's
-- work waits for a person. Only a person turns it, and every turn is recorded with who and when.
-- No level lets found work queue itself. See docs/autonomy.md, The dial.

CREATE TYPE project_autonomy AS ENUM (
    -- Every batch waits for a person's approval, and so does every change to a tracker.
    'approve_every_batch',
    -- A batch that traces to a person runs; a found one, and every change to a tracker, waits.
    'approve_found_work',
    -- A batch that traces to a person runs, and changes to trackers apply at once; a found
    -- batch still waits.
    'full_autonomy'
);

-- Every project starts at the default, the projects already here too. That includes a project
-- whose Project Manager wrote to its trackers directly: Full autonomy would also let its batches
-- run without a person, which nobody chose, so a person turns its dial up by hand.
ALTER TABLE projects
    ADD COLUMN autonomy project_autonomy NOT NULL DEFAULT 'approve_every_batch';

-- Full autonomy is now how a Project Manager writes directly.
ALTER TABLE projects DROP COLUMN manager_writes_directly;

-- Each turn of a project's dial, by the person who turned it. The newest is who set the level
-- the project has; a project with none is still at the default it started with.
CREATE TABLE project_autonomy_changes (
    -- Generated by the API (UUIDv7), so ids order a project's changes the way they were made.
    id UUID PRIMARY KEY,
    project_id UUID NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    previous_autonomy project_autonomy NOT NULL,
    autonomy project_autonomy NOT NULL,
    created_by UUID NOT NULL REFERENCES users (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- Choosing the level a project already has changes nothing, so it records nothing.
    CONSTRAINT project_autonomy_changes_moves CHECK (previous_autonomy <> autonomy)
);

-- A project's newest change, which its page shows.
CREATE INDEX project_autonomy_changes_newest ON project_autonomy_changes (project_id, id DESC);
