-- Findings: work a worker or a Project Manager noticed that nobody asked for. Agent-found work
-- never queues itself, so it is reported here for a person to accept or dismiss, never filed or
-- submitted. Accepting makes an action item, owes its issue, and proposes a batch; dismissing is
-- remembered, so the same finding is never raised twice. See docs/autonomy.md, Findings, and
-- docs/engine.md, Findings.

CREATE TYPE finding_state AS ENUM (
    -- Waits on the project's Findings list for a person.
    'open',
    -- A person accepted it: it is an action item and a proposed batch.
    'accepted',
    -- A person dismissed it; it stays, so the same finding is never raised again.
    'dismissed'
);

CREATE TYPE finding_cost AS ENUM (
    -- An hour of a worker's time or less.
    'small',
    -- About one batch's work.
    'medium',
    -- More than one batch.
    'large'
);

CREATE TABLE findings (
    -- Generated by the API (UUIDv7), so ids order findings the way they were first reported.
    id UUID PRIMARY KEY,
    project_id UUID NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    -- What the finding is and where, normalized and hashed by the API
    -- (`crate::models::finding::fingerprint`), as 64 hex digits. One per project, so a second
    -- report of the same finding, by any worker, after any restart, finds the first.
    fingerprint TEXT NOT NULL,
    title TEXT NOT NULL,
    -- What was seen, why it matters, and what fixing it involves.
    detail TEXT NOT NULL,
    -- The repository it was seen in, when it was seen in one.
    repository_url TEXT,
    -- Where in it, or where else: a path, a URL, or a place's name.
    location TEXT NOT NULL,
    cost finding_cost NOT NULL,
    state finding_state NOT NULL DEFAULT 'open',
    -- Who reported it first: a worker, by its batch, or a Project Manager, by its turn. Each is
    -- kept only while that row is.
    work_batch_id UUID REFERENCES work_batches (id) ON DELETE SET NULL,
    project_manager_turn_id UUID REFERENCES project_manager_turns (id) ON DELETE SET NULL,
    -- How many times it was reported, the first included, whatever it stood at then.
    reports INTEGER NOT NULL DEFAULT 1,
    last_reported_at TIMESTAMPTZ NOT NULL,
    -- The person who accepted or dismissed it, and when; set exactly once it is not open.
    decided_by UUID REFERENCES users (id),
    decided_at TIMESTAMPTZ,
    -- Why a person dismissed it, when they said; an agent reporting it again is told.
    dismissal_reason TEXT,
    -- What accepting made: its action item and its proposed batch.
    action_item_id UUID REFERENCES action_items (id) ON DELETE SET NULL,
    accepted_batch_id UUID REFERENCES work_batches (id) ON DELETE SET NULL,
    -- The machine user of whoever reported it first: the coding agent for a worker, the Project
    -- Managers' for a Project Manager.
    created_by UUID NOT NULL REFERENCES users (id),
    created_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT findings_once UNIQUE (project_id, fingerprint),
    CONSTRAINT findings_fingerprint_shape CHECK (fingerprint ~ '^[0-9a-f]{64}$'),
    CONSTRAINT findings_title_length CHECK (char_length(title) BETWEEN 1 AND 200),
    CONSTRAINT findings_detail_length CHECK (char_length(detail) BETWEEN 1 AND 10000),
    CONSTRAINT findings_repository_url_length CHECK (char_length(repository_url) BETWEEN 1 AND 2048),
    CONSTRAINT findings_location_length CHECK (char_length(location) BETWEEN 1 AND 500),
    CONSTRAINT findings_one_reporter CHECK (num_nonnulls(work_batch_id, project_manager_turn_id) <= 1),
    CONSTRAINT findings_reports_count CHECK (reports >= 1),
    CONSTRAINT findings_decided_once_not_open CHECK (
        (state = 'open') = (decided_by IS NULL AND decided_at IS NULL)
    ),
    CONSTRAINT findings_dismissal_reason CHECK (
        dismissal_reason IS NULL
        OR (state = 'dismissed' AND char_length(dismissal_reason) BETWEEN 1 AND 2000)
    ),
    CONSTRAINT findings_accepted_made CHECK (
        (action_item_id IS NULL AND accepted_batch_id IS NULL) OR state = 'accepted'
    )
);

-- A project's Findings list and its count, and every project's count for Elysia.
CREATE INDEX findings_open ON findings (project_id, id) WHERE state = 'open';

-- Accepting a finding is a person's own action, so the issue it owes is filed as that person,
-- beside the changeset proposers who owe the others.
ALTER TABLE action_item_issue_filings
    DROP CONSTRAINT action_item_issue_filings_filed_by_shape,
    ADD CONSTRAINT action_item_issue_filings_filed_by_shape
        CHECK (filed_by ~ '^(user:[0-9a-f-]{36}|elysia|session:[0-9]+|project_manager:[0-9a-f-]{36})$');
