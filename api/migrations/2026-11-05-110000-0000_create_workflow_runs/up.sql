-- Workflow runs and their step jobs: the engine's queue of background work. A run is one
-- workflow on one source; each of its steps is its own job row, which the engine claims with
-- FOR UPDATE SKIP LOCKED, runs under a lease it renews, and retries with backoff. See
-- docs/engine.md, Runs.

-- Where a run stands, derived from its steps every time one of them moves.
CREATE TYPE workflow_run_state AS ENUM (
    -- No step has started yet.
    'queued',
    -- A step runs, waits to be claimed, or waits out its backoff before another attempt.
    'running',
    -- A step finished asking a person to look before the run goes on; resuming it continues.
    'held',
    -- A step failed for good, which stops the run with its reason until someone retries or
    -- skips it.
    'failed',
    -- Every step succeeded or was skipped.
    'succeeded'
);

-- Where one step of a run stands.
CREATE TYPE step_job_state AS ENUM (
    -- The run has not reached it yet.
    'pending',
    -- Waiting for the engine to claim it, from `available_at`.
    'queued',
    -- An engine holds it under a lease (`claim_token`, `lease_expires_at`).
    'running',
    -- It finished and asks a person to look before the run goes on.
    'held',
    -- Its last attempt failed and it may not be tried again on its own.
    'failed',
    -- Someone skipped it: the step after it receives the input it would have.
    'skipped',
    'succeeded'
);

CREATE TABLE workflow_runs (
    -- Generated by the API or the engine (UUIDv7), so runs order as they were started.
    id UUID PRIMARY KEY,
    -- The workflow's name in code, such as `meeting`. Names, never numbers.
    workflow TEXT NOT NULL CHECK (workflow ~ '^[a-z][a-z0-9_]{0,63}$'),
    -- What the run is about: a kind (`meeting`, `timeline_record`) and that thing's id, as
    -- text since sources are keyed differently.
    source_kind TEXT NOT NULL CHECK (source_kind ~ '^[a-z][a-z0-9_]{0,63}$'),
    source_id TEXT NOT NULL CHECK (char_length(source_id) BETWEEN 1 AND 255),
    state workflow_run_state NOT NULL DEFAULT 'queued',
    -- What the first step receives.
    input JSONB NOT NULL,
    -- The failed step's reason, copied here so a list of runs can say why each stopped.
    error TEXT CHECK (char_length(error) BETWEEN 1 AND 2000),
    -- Who or what started it: a person, or the system user or Elysia for what she or a watcher
    -- started.
    created_by UUID NOT NULL REFERENCES users (id),
    created_at TIMESTAMPTZ NOT NULL,
    -- When its first step was first claimed.
    started_at TIMESTAMPTZ,
    -- When it succeeded or failed; cleared when a retry or a skip sets it going again.
    finished_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT workflow_runs_error_exactly_when_failed CHECK (
        (state = 'failed') = (error IS NOT NULL)
    ),
    CONSTRAINT workflow_runs_finished_exactly_when_over CHECK (
        (state IN ('failed', 'succeeded')) = (finished_at IS NOT NULL)
    )
);

SELECT diesel_manage_updated_at('workflow_runs');

-- One run of a workflow on a source at a time, until it succeeds: starting it again answers
-- the run already there, so whatever starts runs may do so as often as it notices the source.
CREATE UNIQUE INDEX workflow_runs_one_live_per_source
    ON workflow_runs (workflow, source_kind, source_id)
    WHERE state <> 'succeeded';

CREATE TABLE step_jobs (
    -- UUIDv7.
    id UUID PRIMARY KEY,
    run_id UUID NOT NULL REFERENCES workflow_runs (id) ON DELETE CASCADE,
    -- Where it falls in its run. Steps are named, never numbered, so this only orders them.
    position INTEGER NOT NULL CHECK (position >= 0),
    -- The step's name in code, such as `fetch_transcript`.
    step TEXT NOT NULL CHECK (step ~ '^[a-z][a-z0-9_]{0,63}$'),
    state step_job_state NOT NULL DEFAULT 'pending',
    -- Set once it is queued: the run's input for its first step, else the output of the step
    -- before it, or that step's own input when it was skipped.
    input JSONB,
    -- What it produced; set exactly when it succeeded or is held.
    output JSONB,
    -- The one line its row collapses to, which the step wrote.
    summary TEXT CHECK (char_length(summary) BETWEEN 1 AND 500),
    -- Why its last attempt failed: while it waits to be tried again, runs again, or failed.
    error TEXT CHECK (char_length(error) BETWEEN 1 AND 2000),
    -- What it wrote as it ran, every attempt's, the newest 64 KiB kept.
    log TEXT NOT NULL DEFAULT '' CHECK (char_length(log) <= 65536),
    -- Claims since it was last queued by its run or a person; bounded by the engine.
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    -- While queued: the earliest it may be claimed, later than now during a backoff.
    available_at TIMESTAMPTZ,
    -- While running: the claim, new at every claim, which fences every write of the attempt
    -- so an engine whose lease ran out cannot record over another's.
    claim_token UUID,
    -- While running: when the claim lapses unless renewed. An engine that died stops renewing,
    -- and its step is claimed again once this passes.
    lease_expires_at TIMESTAMPTZ,
    -- When its last attempt started and when it last ended.
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT step_jobs_one_per_position UNIQUE (run_id, position),
    CONSTRAINT step_jobs_available_exactly_when_queued CHECK (
        (state = 'queued') = (available_at IS NOT NULL)
    ),
    CONSTRAINT step_jobs_claimed_exactly_when_running CHECK (
        (state = 'running') = (claim_token IS NOT NULL)
        AND (state = 'running') = (lease_expires_at IS NOT NULL)
    ),
    CONSTRAINT step_jobs_input_once_reached CHECK (
        state IN ('pending', 'skipped') OR input IS NOT NULL
    ),
    CONSTRAINT step_jobs_output_exactly_when_produced CHECK (
        (state IN ('succeeded', 'held')) = (output IS NOT NULL)
    ),
    CONSTRAINT step_jobs_error_only_when_failing CHECK (
        error IS NULL OR state IN ('queued', 'running', 'failed')
    )
);

SELECT diesel_manage_updated_at('step_jobs');

-- What the engine claims: queued steps once available, and running ones whose lease lapsed.
CREATE INDEX step_jobs_claimable ON step_jobs (available_at) WHERE state = 'queued';
CREATE INDEX step_jobs_leased ON step_jobs (lease_expires_at) WHERE state = 'running';

-- The history of runs, shaped like learning_events: a run started, and every step a person
-- retried, skipped, or resumed, with who did it.
CREATE TABLE workflow_run_events (
    -- UUIDv7, so entries order as they were written.
    id UUID PRIMARY KEY,
    run_id UUID NOT NULL REFERENCES workflow_runs (id) ON DELETE CASCADE,
    -- The step it was about; NULL for the run's own entries.
    step_job_id UUID REFERENCES step_jobs (id) ON DELETE CASCADE,
    -- `started`, `retried`, `skipped`, or `resumed`. Text rather than an enum, so a later kind
    -- needs no enum migration.
    kind TEXT NOT NULL CHECK (kind ~ '^[a-z][a-z_]{0,63}$'),
    created_by UUID NOT NULL REFERENCES users (id),
    -- Shaped by `kind`; see docs/engine.md, Runs.
    data JSONB NOT NULL CHECK (jsonb_typeof(data) = 'object'),
    created_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX workflow_run_events_run_id_idx ON workflow_run_events (run_id, id);
