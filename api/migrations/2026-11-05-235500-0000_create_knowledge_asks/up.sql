-- Questions people ask the knowledge base for a written answer (`knowledge_ask`), each answered by
-- a text turn on the runner that may only state what the passages it was given say, citing them.
-- The API searches as the person asks and keeps what the search offered; the engine writes the
-- answer and checks every citation against that offer. See docs/knowledge.md, Asking.

CREATE TYPE knowledge_ask_state AS ENUM (
    -- Waiting for the engine to take it.
    'queued',
    -- Its turn is writing the answer.
    'running',
    -- Answered: `answer` holds the claims and the passages they cite.
    'answered',
    -- No answer could be written: `error` says why.
    'failed'
);

CREATE TABLE knowledge_asks (
    -- Generated by the API (UUIDv7); also the id of the turn that answers it.
    id UUID PRIMARY KEY,
    -- Who asked: whose ask it is, the only person who reads it back, and whose budget it spent.
    created_by UUID NOT NULL REFERENCES users (id),
    -- The question, which was also the search's query, so it is held to the search's length.
    question TEXT NOT NULL CHECK (char_length(question) BETWEEN 1 AND 500),
    -- The search's filters as they were asked for (`sources`, `project`, `person`, `from`, `to`),
    -- so the answer can say what it was narrowed to. Never access control.
    filters JSONB NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(filters) = 'object'),
    -- The passages the search offered, in order, as `{ documentId, position }`: the prompt labels
    -- the first P1, the next P2, and an answer may cite only these. References, never text: a
    -- passage's text stays in the index and leaves with its record.
    passages JSONB NOT NULL CHECK (jsonb_typeof(passages) = 'array'),
    -- Whether the search could rank by meaning as well as by words.
    searched_by_meaning BOOLEAN NOT NULL,
    state knowledge_ask_state NOT NULL DEFAULT 'queued',
    -- The checked answer: its claims, each citing sources by number, and the sources.
    answer JSONB CHECK (jsonb_typeof(answer) = 'object'),
    error TEXT CHECK (char_length(error) BETWEEN 1 AND 2000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- When its turn started; an ask the search found nothing for is answered without one.
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,

    CONSTRAINT knowledge_asks_answer_set CHECK ((answer IS NOT NULL) = (state = 'answered')),
    CONSTRAINT knowledge_asks_error_set CHECK ((error IS NOT NULL) = (state = 'failed')),
    CONSTRAINT knowledge_asks_finished_at_set
        CHECK ((finished_at IS NULL) = (state IN ('queued', 'running'))),
    CONSTRAINT knowledge_asks_started_at_set CHECK (state <> 'running' OR started_at IS NOT NULL)
);

-- A person's asks, newest first: their list, and what they asked within the last hour.
CREATE INDEX knowledge_asks_asked ON knowledge_asks (created_by, created_at DESC);

-- What the engine has still to answer, oldest first.
CREATE INDEX knowledge_asks_waiting ON knowledge_asks (created_at)
    WHERE state IN ('queued', 'running');
